function humanizeLabel(raw: string): string {
  const tail = raw.includes('.') ? raw.slice(raw.lastIndexOf('.') + 1) : raw;
  const spaced = tail.replace(/_/g, ' ');
  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}

/** Translation helpers for values that come from upstream catalog metadata. */
export interface LabelTranslator {
  /** type_name or advanced-tree path segment, e.g. "body", "weapon". */
  category(value: string): string;
  /** body type value, e.g. "male". */
  bodyType(value: string): string;
  /** animation name, e.g. "walk". */
  anim(value: string): string;
  /** asset display name, e.g. "Plate armor". */
  itemName(value: string): string;
  /** color key, e.g. "lpcr.tan", "red", "fur_black". */
  color(value: string): string;
  /** asset variant key, e.g. "axe", "longsword_alt". */
  variant(value: string): string;
  /** Asset-owned channel ID with an optional author-facing label. */
  channel(value: string, authoredLabel?: string): string;
  /** Localised display name by item ID with safe fallbacks. */
  catalogItemName(item: Pick<ItemDefinition, 'name' | 'display_name' | 'itemId'>): string;
}

/**
 * Translator for catalog-derived strings. English returns every value
 * unchanged; zh-TW looks up the maps with a raw-value fallback.
 */
export function createLabelTranslator(locale: Locale): LabelTranslator {
  if (locale !== 'zh-TW') {
    const raw = (value: string): string => value;
    return {
      category: raw,
      bodyType: humanizeLabel,
      anim: raw,
      itemName: raw,
      catalogItemName: (item) => item.display_name ?? item.name,
      color: humanizeLabel,
      variant: humanizeLabel,
      channel: (value, authoredLabel) =>
        authoredLabel ?? humanizeLabel(value.replace(/^_+|_+$/g, '')),
    };
  }
  return {
    // Category keys (type names / tree path segments) can arrive in mixed
    // case; normalise. Body type, anim and item names keep their casing.
    category: (value) => CATEGORY_LABELS_ZH[value.toLowerCase()] ?? value,
    bodyType: (value) => BODY_TYPE_LABELS_ZH[value] ?? value,
    anim: (value) => ANIM_LABELS_ZH[value] ?? value,
    itemName: (value) => ITEM_NAME_LABELS_ZH[value] ?? value,
    catalogItemName: (item) =>
      ITEM_DISPLAY_NAMES_ZH[item.itemId ?? ''] ??
      ITEM_NAME_LABELS_ZH[item.name] ??
      item.display_name ??
      item.name,
    color: (value) => {
      const lower = value.toLowerCase();
      if (COLOR_LABELS_ZH[lower] !== undefined) {
        return COLOR_LABELS_ZH[lower];
      }
      const lastDot = lower.lastIndexOf('.');
      if (lastDot !== -1) {
        const suffix = lower.slice(lastDot + 1);
        if (COLOR_LABELS_ZH[suffix] !== undefined) {
          return COLOR_LABELS_ZH[suffix];
        }
      }
      return humanizeLabel(value);
    },
    variant: (value) =>
      VARIANT_LABELS_ZH[value.toLowerCase()] ?? humanizeLabel(value),
    channel: (value, authoredLabel) => {
      const translatedAuthored = authoredLabel
        ? CHANNEL_LABELS_ZH[authoredLabel.toLowerCase()]
        : undefined;
      return translatedAuthored
        ?? CATEGORY_LABELS_ZH[value.toLowerCase()]
        ?? authoredLabel
        ?? humanizeLabel(value.replace(/^_+|_+$/g, ''));
    },
  };
}
